function proposalOutput(title: string, headings: string[], keywords: string[]): string {
  return JSON.stringify({
    title,
    executiveSummary: `${keywords.join(", ")} define the measurable business outcome.`,
    sections: headings.map((heading) => ({
      heading,
      body: `${heading} addresses ${keywords.join(", ")} with a clear owner and next step.`,
      bullets: [`Validated ${keywords[0]}`, `Measured ${keywords[1] || keywords[0]}`],
    })),
  })
}

function pitchOutput(company: string, headings: string[], keywords: string[]): string {
  return JSON.stringify({
    company,
    tagline: `${keywords[0]} for a clearer market outcome`,
    slides: headings.map((title) => ({
      title,
      bullets: [`${keywords[0]} is the core customer need`, `${keywords[1] || keywords[0]} supports adoption`],
      visualSuggestion: `Show ${keywords.join(" and ")}`,
      speakerNotes: `Explain how ${keywords.join(", ")} connect to the decision.`,
    })),
  })
}

